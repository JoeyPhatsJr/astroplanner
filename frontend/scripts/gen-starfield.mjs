// Generates src/styles/starfield.css: a static, seeded starfield made of CSS radial gradients.
// Run: node scripts/gen-starfield.mjs   (output is committed; rerun only to change the look)
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Small deterministic PRNG so the starfield never changes between builds.
function mulberry32(seed) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(20261102);

// Three tiles of different sizes overlap so the repetition is not noticeable.
const TILES = [
  { w: 613, h: 647, n: 14, sizes: [1.2, 1.5, 1.8, 2.2], alpha: [0.55, 0.95] }, // sparse brighter stars
  { w: 431, h: 463, n: 26, sizes: [0.9, 1, 1.2, 1.4], alpha: [0.3, 0.7] },
  { w: 293, h: 311, n: 24, sizes: [0.8, 0.9, 1], alpha: [0.18, 0.45] }, // faint background dust
];

const layers = [];
const sizes = [];
for (const tile of TILES) {
  for (let i = 0; i < tile.n; i++) {
    const x = Math.round(rand() * tile.w);
    const y = Math.round(rand() * tile.h);
    const r = tile.sizes[Math.floor(rand() * tile.sizes.length)];
    const a = (tile.alpha[0] + rand() * (tile.alpha[1] - tile.alpha[0])).toFixed(2);
    layers.push(
      `radial-gradient(${r}px ${r}px at ${x}px ${y}px, rgb(var(--star-rgb) / calc(${a} * var(--star-k))), transparent 70%)`,
    );
    sizes.push(`${tile.w}px ${tile.h}px`);
  }
}

const css = `/* GENERATED by scripts/gen-starfield.mjs (seed 20261102). Do not edit by hand. */
/* ${layers.length} stars across 3 overlapping tiles. Colours come from theme variables so
   night-vision mode turns the stars red and dimmer. Static: no animation. */
body::before {
  content: "";
  position: fixed;
  inset: 0;
  z-index: -1;
  pointer-events: none;
  background-image:
    var(--sky-glow-top),
    var(--sky-glow-corner),
    ${layers.join(",\n    ")};
  background-size:
    100% 100%,
    100% 100%,
    ${sizes.join(",\n    ")};
}
`;

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/styles/starfield.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`wrote ${layers.length} stars to ${out}`);
